/** Modifier DOM codes released on keyboard reset / blur */
const MODIFIER_CODES: string[] = [
	'ShiftLeft',
	'ShiftRight',
	'ControlLeft',
	'ControlRight',
	'AltLeft',
	'AltRight',
	'MetaLeft',
	'MetaRight'
];

/**
 * @param code - KeyboardEvent.code
 * @param peerPlatform - PeerInfo.platform (e.g. "Windows", "Linux")
 */
function codeToScancode(code: string, peerPlatform?: string | null): number | null {
	const platform = (peerPlatform || '').toLowerCase();
	if (platform === 'linux') {
		return CODE_TO_LINUX_SCAN[code] ?? null;
	}
	// Default / Windows / macOS remote on Windows host
	return CODE_TO_WIN_SCAN[code] ?? null;
}

export const RDKeyboardScancode = {
	CODE_TO_WIN_SCAN,
	CODE_TO_LINUX_SCAN,
	MODIFIER_CODES,
	codeToScancode
};

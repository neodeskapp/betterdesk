//go:build ignore

// gen_allowlist writes allowlist.go from the template web-nodejs/.env.example:
// every key on a line "KEY=" or "# KEY=", as the old console read it.
//
//	cd betterdesk-server/console/managedconfig && go generate
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
)

func main() {
	template, err := os.ReadFile("../../../web-nodejs/.env.example")
	if err != nil {
		log.Fatal(err)
	}
	line := regexp.MustCompile(`(?m)^[ \t]*#?[ \t]*([A-Z][A-Z0-9_]*)[ \t]*=`)
	seen := map[string]bool{}
	var keys []string
	for _, m := range line.FindAllSubmatch(template, -1) {
		if key := string(m[1]); !seen[key] {
			seen[key] = true
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_allowlist.go from web-nodejs/.env.example; DO NOT EDIT.\n\n")
	out.WriteString("package managedconfig\n\n")
	out.WriteString("// allowlist is every key the template .env.example names.\n")
	out.WriteString("var allowlist = []string{\n")
	for _, key := range keys {
		fmt.Fprintf(&out, "\t%q,\n", key)
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("allowlist.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

package authn

import (
	"testing"
)

// TestAdminPasswordLineWithoutAValue: an "Admin Password:" line without a
// value gives no password; the line after it is not taken in its place
// (BUGS.md AN4).
func TestAdminPasswordLineWithoutAValue(t *testing.T) {
	for _, c := range []struct{ name, content, want string }{
		{"value on the line", "Admin Username: admin\nAdmin Password: s3cret\n", "s3cret"},
		{"value on the next line", "Admin Username: admin\nAdmin Password:\nGenerated by: x\n", ""},
		{"value after blank lines", "Admin Password:\n\n\nsecond\n", ""},
		{"white space, then the next line", "Admin Password:   \r\nnext\n", ""},
		{"line ends of other kinds", "Admin Password: next", ""},
	} {
		s := pureService()
		files := newMemFS()
		files.place(fileVector{Path: "/keys/.admin_credentials", Content: c.content})
		s.fs, s.set.KeysPath = files, "/keys"
		if got := s.ReadAdminCredentialsFile(); got != c.want {
			t.Errorf("%s: %q, want %q", c.name, got, c.want)
		}
	}
}

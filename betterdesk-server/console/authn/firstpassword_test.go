package authn

import (
	"context"
	"strings"
	"testing"

	"github.com/unitronix/betterdesk-server/console/store"
	"github.com/unitronix/betterdesk-server/console/store/storetest"
)

// L77: once the admin changed the first password, the files that hold it
// are removed and a note without the password stays in their place.
// Another account's change leaves them alone.
func TestChangePasswordRemovesTheFirstPasswordFile(t *testing.T) {
	storetest.EachOrigin(t, func(t *testing.T, db *store.DB, _ storetest.Origin) {
		ctx := context.Background()
		files := newMemFS()
		s, _, _ := testService(t, db, func(o *Options) {
			o.FS = files
			o.Settings = Settings{KeysPath: "/opt/rustdesk", DataDir: "/app/data"}
		})
		const first = "first-pass-0123456789"
		content := "Admin Username: admin\nAdmin Password: " + first + "\nGenerated by: BetterDesk Docker bootstrap\n"
		files.place(fileVector{Path: "/opt/rustdesk", Dir: true})
		files.place(fileVector{Path: "/app/data", Dir: true})
		files.place(fileVector{Path: "/opt/rustdesk/.admin_credentials", Content: content})
		files.place(fileVector{Path: "/app/data/.admin_credentials", Content: content})
		admin := addUser(t, s, "admin", first, "admin", "local")
		other := addUser(t, s, "operator1", "operator-pass-1", "operator", "local")

		if err := s.ChangePassword(ctx, other, "operator-pass-1", "operator-pass-2"); err != nil {
			t.Fatal(err)
		}
		if !files.Exists("/opt/rustdesk/.admin_credentials") || !files.Exists("/app/data/.admin_credentials") {
			t.Fatal("another account's password change removed the admin's first password")
		}

		if err := s.ChangePassword(ctx, admin, "wrong-current-pass", "a-new-pass-123"); err != ErrWrongPassword {
			t.Fatalf("change with a wrong current password: %v", err)
		}
		if !files.Exists("/opt/rustdesk/.admin_credentials") {
			t.Fatal("a refused change removed the first password")
		}

		if err := s.ChangePassword(ctx, admin, first, "a-new-pass-123"); err != nil {
			t.Fatal(err)
		}
		for _, dir := range []string{"/opt/rustdesk", "/app/data"} {
			if files.Exists(dir + "/.admin_credentials") {
				t.Errorf("%s/.admin_credentials is still there after the admin changed the password", dir)
			}
			note, err := files.ReadFile(dir + "/" + credentialsRemovedFile)
			if err != nil {
				t.Errorf("no note in %s: %v", dir, err)
				continue
			}
			if strings.Contains(string(note), first) {
				t.Errorf("the note in %s holds the password", dir)
			}
		}
	})
}
